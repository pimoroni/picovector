  pattern_brush_t::pattern_brush_t(const color_t& c1, const color_t& c2, uint8_t pattern_index) : c1(c1._p), c2(c2._p) {
    memcpy(this->p, &patterns[pattern_index], sizeof(uint8_t) * 8);
  }

  pattern_brush_t::pattern_brush_t(const color_t& c1, const color_t& c2, uint8_t *pattern) : c1(c1._p), c2(c2._p) {
    memcpy(this->p, pattern, sizeof(uint8_t) * 8);
  }

  void pattern_brush_t::blend_spans(image_t *target, int i0, int i1, int step) {
    pattern_brush_t *p = this;
    const pv_span *spans = _spans();
    // Both colours are invariant across the batch, so the target's global alpha
    // folds into them once here rather than per pixel.
    pixel_t c1 = fold_target_alpha(target, p->c1);
    pixel_t c2 = fold_target_alpha(target, p->c2);
    for(int i = i0; i < i1; i += step) {
      int x = spans[i].x, y = spans[i].y, w = spans[i].w;
      pv_store_t *dst = (pv_store_t*)target->ptr(x, y);

      while(w--) {
        uint8_t u = 7 - (x & 0b111);
        uint8_t v = y & 0b111;
        uint8_t bit = p->p[v];

        uint32_t src = bit & (1 << u) ? c1 : c2;

        pv_store(dst, blend_over_premul(pv_load(dst), src));
        dst++;
        x++;
      }
    }
  }

  void pattern_brush_t::blend_masked_spans(image_t *target, int i0, int i1, int step) {
    pattern_brush_t *p = this;
    const pv_masked_span *spans = _masked_spans();
    pixel_t c1 = fold_target_alpha(target, p->c1);
    pixel_t c2 = fold_target_alpha(target, p->c2);
    for(int i = i0; i < i1; i += step) {
      int x = spans[i].x, y = spans[i].y, w = spans[i].w;
      uint8_t *mask = (uint8_t*)spans[i].mask;
      pv_store_t *dst = (pv_store_t*)target->ptr(x, y);

      while(w--) {
        uint32_t m = *mask++;
        if(m) {
          uint8_t u = 7 - (x & 0b111);
          uint8_t v = y & 0b111;
          uint8_t bit = p->p[v];

          pv_blend_masked(dst, bit & (1 << u) ? c1 : c2, m);
        }
        dst++;
        x++;
      }
    }
  }

